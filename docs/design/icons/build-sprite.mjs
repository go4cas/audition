// Builds the Audition icon sprite from Phosphor Icons (MIT, see PHOSPHOR-LICENSE).
//
// Usage (Bun or Node, no install needed beyond the unpacked package):
//   npm pack @phosphor-icons/core@2.1.1 && tar xzf phosphor-icons-core-2.1.1.tgz
//   bun docs/design/icons/build-sprite.mjs ./package
//
// It reads only the icons listed below and writes two files next to this script:
//   sprite.svg  an SVG sprite: <symbol id="i-<name>"> per icon, for <use href="#i-name">
//   icons.js    the same sprite as a JS string that injects itself into the page,
//               so the wireframes work when opened straight from disk (file://).
// The app vendors these generated files, so Phosphor is never a runtime dependency.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = process.argv[2];
if (!pkg) { console.error("Pass the path to the unpacked @phosphor-icons/core package."); process.exit(1); }

// [weight, phosphor name, our id]. Regular for UI, fill for state, duotone for empty states.
